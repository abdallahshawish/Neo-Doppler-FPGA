#!/usr/bin/env python3
"""
gen_tables.py - generates the constant tables used by the RTL.

Outputs (all fully synthesizable, no $readmemh / file dependency):
  rtl/pkg/aes_pkg.sv       AES S-box, xtime, round functions, Rcon
  rtl/dsp/twiddle_rom.sv   FFT twiddle factors  (cos, sin) in Q1.15
  rtl/dsp/window_rom.sv    Hann window in Q1.15 (unsigned)

Usage:  python3 scripts/gen_tables.py [--fft-log2 8]
"""
import argparse
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent


# --------------------------------------------------------------------------
# AES S-box (computed from first principles: GF(2^8) inverse + affine map)
# --------------------------------------------------------------------------
def gf_mul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p


def build_sbox():
    inv = [0] * 256
    for x in range(1, 256):
        for y in range(1, 256):
            if gf_mul(x, y) == 1:
                inv[x] = y
                break
    sbox = []
    for x in range(256):
        b = inv[x]
        s = b
        for sh in range(1, 5):
            s ^= ((b << sh) | (b >> (8 - sh))) & 0xFF
        sbox.append(s ^ 0x63)
    assert sbox[0x00] == 0x63 and sbox[0x01] == 0x7C and sbox[0x53] == 0xED
    return sbox


AES_PKG_TEMPLATE = """\
// =============================================================================
// AUTO-GENERATED by scripts/gen_tables.py - DO NOT EDIT BY HAND
// -----------------------------------------------------------------------------
// Package : aes_pkg
// Purpose : AES-128 (FIPS-197) primitives: S-box, ShiftRows, MixColumns and
//           the key-schedule step. Byte i of a 128-bit block sits at
//           bits [127-8*i -: 8]  (byte 0 = most-significant byte).
//           State matrix is column-major: s[r][c] = byte (r + 4*c).
// =============================================================================
`ifndef AES_PKG_SV
`define AES_PKG_SV

package aes_pkg;

  // ---------------------------------------------------------------- S-box ---
  function automatic logic [7:0] sbox(input logic [7:0] x);
    case (x)
{sbox_cases}
      default: sbox = 8'h00;
    endcase
  endfunction

  // ------------------------------------------------------------- GF(2^8) ----
  function automatic logic [7:0] xtime(input logic [7:0] x);
    xtime = {{x[6:0], 1'b0}} ^ (x[7] ? 8'h1B : 8'h00);
  endfunction

  // ------------------------------------------------------------ SubBytes ----
  function automatic logic [127:0] sub_bytes(input logic [127:0] s);
    logic [127:0] r;
    for (int i = 0; i < 16; i++)
      r[127-8*i -: 8] = sbox(s[127-8*i -: 8]);
    return r;
  endfunction

  // ----------------------------------------------------------- ShiftRows ----
  // new(r,c) = old(r, (c + r) mod 4)
  function automatic logic [127:0] shift_rows(input logic [127:0] s);
    logic [127:0] r;
    for (int c = 0; c < 4; c++)
      for (int row = 0; row < 4; row++)
        r[127-8*(row+4*c) -: 8] = s[127-8*(row+4*((c+row)%4)) -: 8];
    return r;
  endfunction

  // ---------------------------------------------------------- MixColumns ----
  function automatic logic [127:0] mix_columns(input logic [127:0] s);
    logic [127:0] r;
    logic [7:0] a0, a1, a2, a3;
    for (int c = 0; c < 4; c++) begin
      a0 = s[127-8*(4*c+0) -: 8];
      a1 = s[127-8*(4*c+1) -: 8];
      a2 = s[127-8*(4*c+2) -: 8];
      a3 = s[127-8*(4*c+3) -: 8];
      r[127-8*(4*c+0) -: 8] = xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3;
      r[127-8*(4*c+1) -: 8] = a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3;
      r[127-8*(4*c+2) -: 8] = a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3);
      r[127-8*(4*c+3) -: 8] = (xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3);
    end
    return r;
  endfunction

  // ---------------------------------------------------------- Key schedule --
  function automatic logic [7:0] rcon(input logic [3:0] round);  // round = 1..10
    case (round)
      4'd1:    rcon = 8'h01;
      4'd2:    rcon = 8'h02;
      4'd3:    rcon = 8'h04;
      4'd4:    rcon = 8'h08;
      4'd5:    rcon = 8'h10;
      4'd6:    rcon = 8'h20;
      4'd7:    rcon = 8'h40;
      4'd8:    rcon = 8'h80;
      4'd9:    rcon = 8'h1B;
      4'd10:   rcon = 8'h36;
      default: rcon = 8'h00;
    endcase
  endfunction

  function automatic logic [31:0] sub_word(input logic [31:0] w);
    sub_word = {{sbox(w[31:24]), sbox(w[23:16]), sbox(w[15:8]), sbox(w[7:0])}};
  endfunction

  // One step of the AES-128 key schedule: round key (n-1) -> round key (n).
  function automatic logic [127:0] next_round_key(input logic [127:0] k,
                                                  input logic [3:0]   round);
    logic [31:0] w0, w1, w2, w3, t, n0, n1, n2, n3;
    w0 = k[127:96]; w1 = k[95:64]; w2 = k[63:32]; w3 = k[31:0];
    t  = sub_word({{w3[23:0], w3[31:24]}}) ^ {{rcon(round), 24'h000000}};
    n0 = w0 ^ t;
    n1 = w1 ^ n0;
    n2 = w2 ^ n1;
    n3 = w3 ^ n2;
    return {{n0, n1, n2, n3}};
  endfunction

endpackage : aes_pkg

`endif
"""


def gen_aes_pkg():
    sbox = build_sbox()
    lines = []
    for i, v in enumerate(sbox):
        lines.append(f"      8'h{i:02X}: sbox = 8'h{v:02X};")
    out = AES_PKG_TEMPLATE.format(sbox_cases="\n".join(lines))
    (ROOT / "rtl/pkg/aes_pkg.sv").write_text(out)


# --------------------------------------------------------------------------
# FFT twiddle ROM  (idx 0..N/2-1):  cos(2*pi*idx/N), sin(2*pi*idx/N)  Q1.15
# --------------------------------------------------------------------------
def q15(x):
    v = int(round(x * 32768.0))
    return max(-32768, min(32767, v))


def gen_twiddle(log2n):
    n = 1 << log2n
    half = n // 2
    cases = []
    for i in range(half):
        c = q15(math.cos(2 * math.pi * i / n)) & 0xFFFF
        s = q15(math.sin(2 * math.pi * i / n)) & 0xFFFF
        cases.append(f"      {log2n - 1}'d{i}: {{tw_cos, tw_sin}} = {{16'h{c:04X}, 16'h{s:04X}}};")
    text = f"""\
// =============================================================================
// AUTO-GENERATED by scripts/gen_tables.py - DO NOT EDIT BY HAND
// Module  : twiddle_rom
// Purpose : FFT twiddle factors W_N^k = cos(2*pi*k/N) - j*sin(2*pi*k/N),
//           k = 0 .. N/2-1, stored as signed Q1.15 (cos, sin). N = {n}.
// =============================================================================
module twiddle_rom (
  input  logic [{log2n - 2}:0]       addr,
  output logic signed [15:0] tw_cos,
  output logic signed [15:0] tw_sin
);
  always_comb begin
    case (addr)
{chr(10).join(cases)}
      default: {{tw_cos, tw_sin}} = 32'h0;
    endcase
  end
endmodule
"""
    (ROOT / "rtl/dsp/twiddle_rom.sv").write_text(text)


def gen_window(log2n):
    n = 1 << log2n
    cases = []
    for i in range(n):
        w = 0.5 * (1.0 - math.cos(2 * math.pi * i / (n - 1)))
        v = max(0, min(32767, int(round(w * 32767.0))))
        cases.append(f"      {log2n}'d{i}: win = 16'h{v:04X};")
    text = f"""\
// =============================================================================
// AUTO-GENERATED by scripts/gen_tables.py - DO NOT EDIT BY HAND
// Module  : window_rom
// Purpose : Hann window w[n] = 0.5*(1-cos(2*pi*n/(N-1))), unsigned Q1.15,
//           N = {n}. Reduces spectral leakage before the FFT.
// =============================================================================
module window_rom (
  input  logic [{log2n - 1}:0] addr,
  output logic [15:0] win
);
  always_comb begin
    case (addr)
{chr(10).join(cases)}
      default: win = 16'h0;
    endcase
  end
endmodule
"""
    (ROOT / "rtl/dsp/window_rom.sv").write_text(text)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--fft-log2", type=int, default=8, help="log2 of FFT length")
    a = ap.parse_args()
    gen_aes_pkg()
    gen_twiddle(a.fft_log2)
    gen_window(a.fft_log2)
    print("generated: aes_pkg.sv, twiddle_rom.sv, window_rom.sv (N=%d)" % (1 << a.fft_log2))
